import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

const site=fileURLToPath(new URL('../',import.meta.url));
const backend=process.env.MCN_MAIN_ROOT||fileURLToPath(new URL('../../douyin-monitor-workbench/',import.meta.url));
const {chromium}=createRequire(backend+'package.json')('playwright-core');
const fixture=`import React from 'react';
import {createRoot} from 'react-dom/client';
import {UnifiedWorkMetric} from './components/unified-work-metric';
const sampled='2026-10-23T07:50:00.000Z';
const refreshed='2026-10-12T09:00:00.000Z';
const source={id:'creator-source:2:9',source:'creator-source',likes:30,plays:3000,sourceCumulativeLikes:30,sourceCumulativePlays:3000,sourceRefreshedAt:refreshed};
const platform={id:90,source:null,likes:42,plays:4200,lastObservedAt:sampled,playsEvidence:{mayBePlaceholder:false,note:'公开字段，未独立核验实际播放。'}};
const merged={...platform,id:91,source:'platform-and-creator-source',sourceCumulativeLikes:30,sourceCumulativePlays:3000,sourceRefreshedAt:refreshed};
const fallback={...merged,id:92,likes:null,plays:null};
const placeholder={...merged,id:93,plays:0,playsEvidence:{mayBePlaceholder:true}};
const unavailable={...platform,id:94,likes:null,plays:null};
const scenarios=[['source-only',source],['platform-only',platform],['merged',merged],['fallback',fallback],['placeholder',placeholder],['unavailable',unavailable]];
createRoot(document.getElementById('root')).render(<table><tbody>{scenarios.map(([name,work])=><tr key={name} data-testid={name}><th>{name}</th><td><UnifiedWorkMetric work={work} metric="likes"/></td><td><UnifiedWorkMetric work={work} metric="plays"/></td></tr>)}</tbody></table>);`;
const bundle=await build({stdin:{contents:fixture,resolveDir:site,sourcefile:'unified-work-metric-fixture.tsx',loader:'tsx'},absWorkingDir:site,bundle:true,write:false,outfile:'unified-work-metric-fixture.js',format:'iife',platform:'browser',jsx:'automatic',tsconfig:site+'tsconfig.json',define:{'process.env.NODE_ENV':'"test"'}});
const script=bundle.outputFiles.find(file=>file.path.endsWith('.js')).text;

test('works list uses one adopted value per metric and unfolds both sources without inventing a sample',async()=>{
 const pageSource=readFileSync(site+'app/page.tsx','utf8');
 assert.match(pageSource,/<UnifiedWorkMetric work={x} metric="likes"\/>/);
 assert.match(pageSource,/<UnifiedWorkMetric work={x} metric="plays"\/>/);
 assert.match(pageSource,/presentUnifiedWorkMetric\(a,hSort\)\.value/,'ranking must use the displayed value');
 const browser=await chromium.launch({headless:true,executablePath:process.env.MCN_TEST_CHROME||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--disable-background-networking']});
 try{
  const page=await browser.newPage({viewport:{width:780,height:650},reducedMotion:'reduce'});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',route=>route.request().url()==='http://127.0.0.1:49133/'?route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="zh-CN"><meta charset="utf-8"><div id="root"></div></html>'}):route.abort());
  await page.goto('http://127.0.0.1:49133/');
  await page.addStyleTag({content:readFileSync(site+'app/replica.css','utf8')});
  await page.addScriptTag({content:script});
  const cell=(scenario,metric)=>page.getByTestId(scenario).locator('[data-metric="'+metric+'"]');
  await cell('source-only','likes').locator('strong').waitFor();
  assert.doesNotMatch(await cell('source-only','likes').innerText(),/表格累计参考/,'source channel is not a primary metric label');
  assert.equal(await cell('source-only','likes').getAttribute('data-origin'),'source');
  assert.equal(await cell('source-only','likes').locator('strong').innerText(),'30');
  assert.equal(await cell('platform-only','likes').getAttribute('data-origin'),'platform');
  assert.equal(await cell('platform-only','likes').locator('strong').innerText(),'42');
  assert.equal(await cell('merged','likes').locator('strong').innerText(),'42','same work must not sum 42+30');
  assert.equal(await cell('merged','plays').locator('strong').innerText(),'4,200');
  assert.equal(await cell('fallback','likes').getAttribute('data-origin'),'source');
  assert.equal(await cell('fallback','likes').locator('strong').innerText(),'30');
  assert.equal(await cell('placeholder','plays').getAttribute('data-origin'),'source');
  assert.equal(await cell('placeholder','plays').locator('strong').innerText(),'3,000');
  assert.equal(await cell('unavailable','plays').locator('strong').innerText(),'—');
  await cell('merged','likes').locator('summary').focus();
  await cell('merged','likes').locator('summary').press('Enter');
  const mergedDetails=await cell('merged','likes').innerText();
  assert.match(mergedDetails,/平台点赞：42 · 指标采样 2026\/10\/23 15:50:00（北京）/);
  assert.match(mergedDetails,/原表点赞累计：30 · 表格版本刷新 2026\/10\/12 17:00:00（北京）/);
  assert.match(mergedDetails,/表格刷新时间不是这项指标的采样时间/);
  await cell('fallback','plays').locator('summary').click();
  const fallbackDetails=await cell('fallback','plays').innerText();
  assert.match(fallbackDetails,/原表播放字段累计：3,000/);
  assert.equal(await cell('fallback','plays').locator(':scope > small').count(),0,'undated adopted value must not inherit an old platform sample date');
  await cell('placeholder','plays').locator('summary').click();
  assert.match(await cell('placeholder','plays').innerText(),/可能是占位/);
  if(process.env.MCN_UNIFIED_WORK_SCREENSHOT)await page.screenshot({path:process.env.MCN_UNIFIED_WORK_SCREENSHOT,fullPage:true});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();}
});
